"""Generate docs/adr/index.md from the decision records of docs/adr/.

Usage:
    python scripts/build_adr_index.py           write the index
    python scripts/build_adr_index.py --check   exit 1 if the index is out of date
"""

import pathlib
import re
import sys

ADR_DIR = pathlib.Path("docs/adr")
INDEX = ADR_DIR / "index.md"
HEADER = """# Decision records

Architecture and method decisions of the project, in the MADR 4.0.0 format ([ADR-0000](0000-use-madr.md)).
This page is generated by `scripts/build_adr_index.py`; do not edit it by hand.

| Record | Decision | Status | Date |
| --- | --- | --- | --- |
"""


def build() -> str:
    rows = []
    for path in sorted(ADR_DIR.glob("[0-9][0-9][0-9][0-9]-*.md")):
        text = path.read_text(encoding="utf-8")
        status = re.search(r"^status: *(.+)$", text, re.MULTILINE)
        date = re.search(r"^date: *(.+)$", text, re.MULTILINE)
        title = re.search(r"^# (.+)$", text, re.MULTILINE)
        if not (status and date and title):
            raise SystemExit(f"{path}: status, date or title missing")
        number = path.name[:4]
        rows.append(f"| [ADR-{number}]({path.name}) | {title.group(1)} | {status.group(1)} | {date.group(1)} |")
    return HEADER + "\n".join(rows) + "\n"


def main(argv: list[str]) -> int:
    content = build()
    if "--check" in argv:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current != content:
            print("docs/adr/index.md is out of date: run python scripts/build_adr_index.py")
            return 1
        print("docs/adr/index.md is up to date.")
        return 0
    INDEX.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {INDEX}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
